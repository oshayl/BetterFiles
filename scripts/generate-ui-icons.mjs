#!/usr/bin/env node
/**
 * Generates the UI icon set as PNG data URIs in src/styles/icons.css.
 *
 * WHY NOT INLINE SVG
 * Adobe's docs state UXP's SVG renderer targets "simple icons" and that complex
 * SVGs "may fail to render, or render in unexpected ways"; circle elements are
 * reported broken on the developer forums. In practice EVERY inline <svg> icon
 * rendered as a grey blob in Photoshop 2026.
 *
 * PNG data URIs in CSS `background-image` are proven to work in this plugin -
 * it is how the transparency checkerboard renders. So icons are pixel art,
 * rasterised here.
 *
 * Icons are authored as 16x16 ASCII grids so they can be reviewed and edited in
 * source without a drawing tool. '#' is an opaque pixel, anything else is
 * transparent. Each is emitted twice - black for the light theme, white for the
 * dark theme - and at 2x for retina.
 */
