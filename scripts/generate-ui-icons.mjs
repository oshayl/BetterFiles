// ------------------------------------------------------------- PNG -----

const crcTable = (() => {
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  return table;
})();

function crc32(buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) crc = crcTable[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const typeAndData = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typeAndData));
  return Buffer.concat([length, typeAndData, crc]);
}

function encodePng(width, height, rgba) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 6; // RGBA
  const stride = width * 4;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y += 1) {
    raw[y * (stride + 1)] = 0;
    rgba.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/** Rasterises an ASCII grid at the given pixel scale. */
function render(art, scale, [r, g, b]) {
  const rows = art
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

  const size = 16;
  if (rows.length !== size) {
    throw new Error(`icon must be ${size} rows, found ${rows.length}`);
  }

  const dimension = size * scale;
  const rgba = Buffer.alloc(dimension * dimension * 4, 0);

  for (let y = 0; y < size; y += 1) {
    const row = rows[y];
    if (row.length !== size) {
      throw new Error(`icon row ${y} must be ${size} chars, found ${row.length}`);
    }
    for (let x = 0; x < size; x += 1) {
      if (row[x] !== '#') continue;

      // Expand one source pixel into a scale x scale block.
      for (let dy = 0; dy < scale; dy += 1) {
        for (let dx = 0; dx < scale; dx += 1) {
          const px = x * scale + dx;
          const py = y * scale + dy;
          const offset = (py * dimension + px) * 4;
          rgba[offset] = r;
          rgba[offset + 1] = g;
          rgba[offset + 2] = b;
          rgba[offset + 3] = 255;
        }
      }
    }
  }

  return encodePng(dimension, dimension, rgba);
}

async function main() {
  const BLACK = [10, 10, 10];
  const WHITE = [255, 255, 255];

  const lines = [
    '/*',
    ' * GENERATED FILE - edit scripts/generate-ui-icons.mjs instead.',
    ' *',
    ' * Icons are PNG data URIs rather than inline SVG: UXP renders inline <svg>',
    ' * unreliably (every icon came out as a grey blob), while PNG backgrounds are',
    ' * proven to work. Rendered at 2x and scaled down, so they stay crisp.',
    ' */',
    '',
    '.icon {',
    '  display: inline-block;',
    '  width: 16px;',
    '  height: 16px;',
    '  flex-shrink: 0;',
    '  background-repeat: no-repeat;',
    '  background-position: center center;',
    '  background-size: 16px 16px;',
    '}',
    '',
    '/* Smaller variants for dense rows. */',
    '.icon--sm {',
    '  width: 12px;',
    '  height: 12px;',
    '  background-size: 12px 12px;',
    '}',
    '',
    '.icon--lg {',
    '  width: 24px;',
    '  height: 24px;',
    '  background-size: 24px 24px;',
    '}',
    '',
  ];

  for (const [name, art] of Object.entries(ICONS)) {
    // 2x renders keep the art crisp on retina; CSS scales it to 16px.
    const dark = render(art, 2, BLACK).toString('base64');
    const light = render(art, 2, WHITE).toString('base64');

    lines.push(
      `.theme-light .icon--${name} {`,
      `  background-image: url('data:image/png;base64,${dark}');`,
      '}',
      '',
      `.theme-dark .icon--${name} {`,
      `  background-image: url('data:image/png;base64,${light}');`,
      '}',
      '',
    );
  }

  const outPath = join(root, 'src/styles/icons.css');
  await writeFile(outPath, lines.join('\n'));

  console.log(`[ui-icons] wrote ${Object.keys(ICONS).length} icons -> src/styles/icons.css`);
}

main().catch((error) => {
  console.error(`[ui-icons] failed: ${error.message}`);
  process.exit(1);
});
